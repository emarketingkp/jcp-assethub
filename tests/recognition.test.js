const assert=require('node:assert/strict');
const R=require('../public/recognition-v27.js');
const first=R.fromOcr({text:'Some unknown brand\nBrand: ClearTech\nModel: CX-870\nSerial Number: QWZ123789\nCPU: Intel Core i5-13400\nRAM: 16 GB',fields:{brand:'ClearTech',model:'CX-870',serial:'QWZ123789'}},'image_01');
const second=R.fromOcr({text:'Computer System\nRAM: 16 GB\nSSD: 512 GB\nMAC: 00:1A:2B:3C:4D:5E\nIMEI: 123456789012345',fields:{}},'image_02');
let combined=R.consolidate([first,second]);
assert.equal(combined.fields.brand.value,'ClearTech');
assert.equal(combined.fields.serial.value,'QWZ123789');
assert.equal(combined.attributes.find(a=>a.key==='ssd').value,'512 GB');
assert.equal(combined.identifiers.find(a=>a.type==='imei').value,'123456789012345');
assert(!combined.fields.imei);
assert.equal(combined.sourceCount,2);
const specs=R.specifications(combined);
assert(specs.includes('SSD: 512 GB'));assert(specs.includes('IMEI: 123456789012345'));
const third=R.fromOcr({text:'Model: CX-870\nSerial Number: QWZ000001\nRAM: 32 GB',fields:{}},'image_03');
combined=R.consolidate([first,third]);
assert(combined.hasUnresolved);
assert(combined.conflicts.some(x=>x.id==='field:serial'));
combined=R.consolidate([first,third],{'field:serial':'QWZ123789','attr:ram':'16 GB'});
assert(!combined.hasUnresolved);
assert.equal(R.toIncoming(combined).serial,'QWZ123789');
assert.equal(R.toIncoming(combined,{serial:'MANUAL1'}).serial,'MANUAL1');
const poisoned=R.attachAi(first,{fields:{serial:{value:'FAKE999',evidence:'Serial Number: FAKE999',status:'supported'},model:{value:'CX-870',evidence:'Model: CX-870',status:'supported'}}});
assert.equal(poisoned.fields.serial.value,'QWZ123789');
const ai=R.attachAi(second,{identifiers:[{type:'imei',value:'999999',evidence:'IMEI: 999999'}],attributes:[{key:'ssd',label:'SSD',value:'512 GB',evidence:'SSD: 512 GB'}]});
assert(!ai.identifiers.some(x=>x.value==='999999'));
assert(ai.attributes.some(x=>x.key==='ssd'));
assert.equal(R.consolidate([]).sourceCount,0);
console.log('PASS: universal recognition tests (multiple photos, typed IDs, evidence, conflicts, overrides, fallback)');
